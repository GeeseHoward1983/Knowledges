; =============================================================================
; junk_all.asm  ——  花指令全类型实验靶子（NASM / x86 32-bit / Win32）
; -----------------------------------------------------------------------------
; 用途：把第 1~12 类花指令各做成一个可调用函数，每个函数“无论花指令怎么绕，
;       最终都返回它的编号（1~12）”。便于：
;         1) objdump -d  观察线性扫描(LS)被骗到的错位；
;         2) IDA / Ghidra 观察递归下降(RD)被骗到的错位 / 断图；
;         3) 链接进 driver.c 实际运行，验证返回值仍是正确编号（语义不变）。
;
; 编译（见 build_nasm.bat）：
;   nasm -f win32 junk_all.asm -o junk_all.obj
;   cl driver.c junk_all.obj /Fe:junk_all.exe
;
; 反汇编对比：
;   objdump -d junk_all.obj        ; 线性扫描视角，会在垃圾字节处错位
;   用 IDA 打开 junk_all.exe       ; 递归下降视角
;
; 约定：所有函数 __cdecl，无参，返回 int。导出名前缀下划线（Win32 C 调用约定）。
; =============================================================================

bits 32

global _demo01
global _demo02
global _demo03
global _demo04
global _demo05
global _demo06
global _demo07
global _demo08
global _demo09_seh        ; 类型9纯汇编 SEH 较繁琐，这里给“触发非法指令”的简化版
global _demo10
global _demo11_smc
global _demo12

section .text

; -----------------------------------------------------------------------------
; 类型 1：跳过字节型（EB 01 + 垃圾字节）—— 专打线性扫描
; jmp short 跳过 1 个垃圾字节 0E8h。LS 会把 E8 当 call 头吞掉后续真实指令。
; -----------------------------------------------------------------------------
_demo01:
    jmp short .real
    db 0E8h                 ; junk：0xE8 = call 操作码，最具破坏力
.real:
    mov eax, 1
    ret

; -----------------------------------------------------------------------------
; 类型 2：不透明谓词（xor eax,eax; jz +1; 垃圾）—— 专打递归下降(IDA)
; xor 置 ZF=1，jz 恒真必跳；IDA 探索 fall-through 分支解码垃圾字节而错位。
; -----------------------------------------------------------------------------
_demo02:
    xor eax, eax            ; ZF = 1
    jz short .real          ; 恒真
    db 0E8h                 ; junk（IDA 误当 call）
.real:
    mov eax, 2
    ret

; -----------------------------------------------------------------------------
; 类型 3：互补跳转对（jz + jnz 指向同一目标 = 伪无条件）
; 无论 ZF 取值，必有一条跳转成立；二者之间/之后的垃圾不可达。
; -----------------------------------------------------------------------------
_demo03:
    cmp eax, eax            ; 设置确定标志（ZF=1）
    jz short .real
    jnz short .real         ; 互补兜底：合起来 = 必跳
    db 0E8h                 ; junk
.real:
    mov eax, 3
    ret

; -----------------------------------------------------------------------------
; 类型 4：push/ret 伪跳转 —— 用 ret 当 jmp，断 IDA 的函数边界与 CFG
; push 真实地址再 ret，等价 jmp .real；IDA 见 ret 以为函数结束。
; -----------------------------------------------------------------------------
_demo04:
    push .real
    ret                     ; = jmp .real
    db 0CCh, 0CCh, 0CCh     ; junk(int3)，不可达
.real:
    mov eax, 4
    ret

; -----------------------------------------------------------------------------
; 类型 5：call/pop 取 EIP（GetPC 技巧）—— 扰乱 call/ret 配对分析
; call 下一条把返回地址压栈，pop 取出 = 自身运行地址。
; -----------------------------------------------------------------------------
_demo05:
    call .next              ; E8 00 00 00 00
.next:
    pop  eax                ; eax = 地址(.next)，演示取 EIP
    mov  eax, 5             ; 真实返回值
    ret

; -----------------------------------------------------------------------------
; 类型 6：call + 运行时修改返回地址 —— 静态无法预知 ret 目标
; call 后把栈顶返回地址加上 (.real-.anchor)，ret 落到 .real，跨过中间垃圾。
; -----------------------------------------------------------------------------
_demo06:
    call .anchor
.anchor:
    add dword [esp], (.real - .anchor)   ; 修改返回地址
    ret                                  ; ret 到算出来的 .real
    db 0CCh, 0CCh, 0CCh                   ; junk，被跳过
.real:
    mov eax, 6
    ret

; -----------------------------------------------------------------------------
; 类型 7：间接跳转（mov reg,imm; jmp reg）—— IDA 静态不知 reg 值
; -----------------------------------------------------------------------------
_demo07:
    mov eax, .real
    jmp eax                 ; 间接跳转，目标“悬空”
    db 0E8h, 090h, 090h     ; junk
.real:
    mov eax, 7
    ret

; -----------------------------------------------------------------------------
; 类型 8：重叠指令 —— 用恒跳让 RD 错对齐到指令中部
; xor+jz 恒跳到 .mid；前面那个 0B8h(mov 的操作码) 是误导对齐用的垃圾。
; 若 RD 从 0B8h 开始解码，会把后续真实指令吞进一条 mov imm32。
; -----------------------------------------------------------------------------
_demo08:
    xor eax, eax
    jz short .mid           ; 恒跳，跳过下面那个误导字节
    db 0B8h                 ; 'mov eax, imm32' 的操作码，制造重叠错位
.mid:
    mov eax, 8
    ret

; -----------------------------------------------------------------------------
; 类型 9：异常驱动控制流（简化版：ud2 非法指令）
; 纯汇编装 SEH 链较长，这里用 ud2 触发非法指令异常作演示；
; 真实样本里 handler 会改 CONTEXT.Eip 决定恢复点。完整 SEH 版见 driver.c 的 demo9。
; 注意：此函数单独调用会抛异常，driver.c 里用 __try 包裹调用。
; -----------------------------------------------------------------------------
_demo09_seh:
    mov eax, 9              ; 先放好返回值
    ud2                     ; 0F 0B：非法指令 → 触发异常（演示“隐形跳转”）
    db 0E8h, 0E8h           ; junk，不可达
    ret

; -----------------------------------------------------------------------------
; 类型 10：冗余前缀 / 半前缀干扰
; 多个 66h(操作数大小前缀)叠加一个 nop，合法但撑大指令、迷惑简易 LS。
; -----------------------------------------------------------------------------
_demo10:
    db 66h                  ; 冗余前缀
    db 66h                  ; 再来一个
    nop                     ; 被前缀修饰的 nop，无副作用
    mov eax, 10
    ret

; -----------------------------------------------------------------------------
; 类型 11：自修改代码 SMC（运行时异或解密一小段“代码”再执行）
; int _demo11_smc(unsigned char* rwx, int len)
;   rwx：由 C 侧 VirtualProtect 成 RWX 的缓冲，已填入密文（见 driver.c）。
;   asm 侧负责真正的“自修改 + 跳入执行”：逐字节 XOR 0xAA 解密后 call 进去。
; 密文 12 A1 AA AA AA 69 解密回 B8 0B 00 00 00 C3 (mov eax,11; ret)。
; 说明：原先把密文放 .data 并相对 jmp 的写法有两个坑——.data 默认不可执行(DEP
;       崩溃)、跨节相对 jmp 目标不可靠；故改为 C 分配 RWX、asm 解密执行。
; -----------------------------------------------------------------------------
_demo11_smc:
    push ebp
    mov  ebp, esp
    push esi
    mov  esi, [ebp+8]       ; rwx 指针（参数1）
    mov  ecx, [ebp+12]      ; len（参数2）
    push esi                ; 保存入口地址
.dec:
    xor  byte [esi], 0AAh   ; 逐字节解密（真正的自修改）
    inc  esi
    loop .dec
    pop  eax                ; eax = 解密后代码入口
    call eax                ; 执行解出的 mov eax,11; ret → eax=11
    pop  esi
    mov  esp, ebp
    pop  ebp
    ret

; -----------------------------------------------------------------------------
; 类型 12：花花组合（链式：push/ret → EB01 → 不透明谓词 → 间接跳转）
; 多种手法串联，模拟自动加花引擎的“代码海洋”。最终仍返回 12。
; -----------------------------------------------------------------------------
_demo12:
    push .stage2            ; (4) push/ret
    ret
    db 0CCh                 ; junk
.stage2:
    jmp short .stage3       ; (1) 跳过字节
    db 0E8h                 ; junk
.stage3:
    xor edx, edx            ; (2) 不透明谓词（用 edx，演示寄存器轮换）
    jz short .stage4
    db 0E9h                 ; junk
.stage4:
    mov eax, .real
    jmp eax                 ; (7) 间接跳转
    db 090h, 090h           ; junk
.real:
    mov eax, 12
    ret
